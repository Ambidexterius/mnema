export function invitationMailNotice(status: string | undefined) {
  return status === 'sent'
    ? 'Письмо передано почтовому серверу. Если оно не пришло, проверьте спам или передайте ссылку участнику.'
    : status === 'failed'
      ? 'Приглашение создано. Письмо отправить не удалось. Скопируйте ссылку и передайте её коллеге.'
      : 'Отправка писем пока не настроена. Передайте ссылку участнику.';
}
